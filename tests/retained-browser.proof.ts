import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { once } from 'node:events';
import { mkdir, writeFile } from 'node:fs/promises';
import { createServer } from 'node:net';
import { join, resolve } from 'node:path';
import { serve } from '@hono/node-server';
import { eq } from 'drizzle-orm';
import { chromium, type Browser } from 'playwright';
import { createArtifactStore } from '../packages/artifacts/src/index.ts';
import { artifact, artifactCommand, artifactPublication, artifactRevision, panelSession, session, user } from '../packages/db/src/schema.ts';
import { createPublicationApp } from '../apps/publication/src/http.ts';
import { verifyRetainedArtifact } from '../.agents/skills/verify-artifacts/scripts/retained.ts';
import { fixture } from './helpers.ts';

const evidence = resolve('.test-artifacts/verify-artifacts', `retained-${Date.now()}-${randomBytes(4).toString('hex')}`);
await mkdir(evidence, { recursive: true, mode: 0o700 });
const reservation = createServer().listen(0, '127.0.0.1');
await once(reservation, 'listening');
const address = reservation.address();
assert(address && typeof address === 'object');
await new Promise<void>((done) => reservation.close(() => done()));
const dashboard = `http://localhost:${address.port}`;
let publicationHandler = async (_request: Request) => new Response(null, { status: 503 });
const publicationServer = serve({ fetch: (request) => publicationHandler(request), hostname: '::1', port: 0 });
await once(publicationServer, 'listening');
const publicationAddress = publicationServer.address();
assert(publicationAddress && typeof publicationAddress === 'object');
const publish = `http://[::1]:${publicationAddress.port}`;
const app = await fixture({ dashboard, publishOrigin: publish });
const serviceSecret = randomBytes(32).toString('hex');
const cookieSecret = randomBytes(32).toString('hex');
publicationHandler = createPublicationApp({ DASHBOARD_URL: dashboard, PUBLISH_URL: publish, PUBLICATION_SERVICE_SECRET: serviceSecret, PUBLICATION_COOKIE_SECRET: cookieSecret });
const store = createArtifactStore(app.db, { access: app.config.access, publishOrigin: publish });
const central = await app.db.select().from(session).where(eq(session.userId, app.ownerId)).get();
assert(central);
const actor = { userId: app.ownerId, sessionId: central.id, clientId: 'retained-proof-fixture', scopes: ['artifacts:read', 'artifacts:write', 'artifacts:publish'] };
const first = await store.create(actor, { requestId: randomBytes(16).toString('hex'), snapshot: { metadata: { title: 'Retained browser proof', description: 'Exact saved revision with a newer unpublished head', custom: { retained: true } }, content: { kind: 'html', text: '<h1>Saved retained revision</h1><button id="change">Change cost</button><output id="total">5.00</output><script>document.querySelector("#change").onclick=()=>document.querySelector("#total").textContent="28.40"</script>' }, files: [{ path: 'nested/bytes.bin', mediaType: 'application/octet-stream', encoding: 'base64', data: 'AAH/' }, { path: 'notes.txt', mediaType: 'text/plain', encoding: 'utf8', data: 'Saved retained attachment.\n' }] } });
await store.publish(actor, { requestId: randomBytes(16).toString('hex'), artifactId: first.artifactId, revisionId: first.revision.id, expectedPublicationVersion: 0 });
await store.update(actor, { requestId: randomBytes(16).toString('hex'), artifactId: first.artifactId, expectedRevisionId: first.revision.id, snapshot: { metadata: { title: 'Unpublished newer head', description: 'Verifier must select revision one' }, content: { kind: 'text', text: 'Newer head is not the retained published revision.' }, files: [] } });
const expected = await store.read(actor, { artifactId: first.artifactId, revisionId: first.revision.id });
const client = await app.auth.api.adminCreateOAuthClient({ headers: new Headers({ cookie: app.cookie }), body: { client_name: 'Retained proof dashboard', application_type: 'native', redirect_uris: [`${dashboard}/auth/callback`], token_endpoint_auth_method: 'client_secret_basic', grant_types: ['authorization_code'], response_types: ['code'], scope: 'openid profile', enable_end_session: true, skip_consent: true, require_pkce: true } });
assert(client.client_secret);
const child = spawn(process.execPath, ['apps/dashboard/dist/server/entry.mjs'], { env: { PATH: process.env.PATH, OWNER_EMAIL: app.config.access.ownerEmail, ALLOW_GUEST_ACCESS: String(app.config.access.allowGuests), DATABASE_URL: app.databaseUrl, DATABASE_AUTH_TOKEN: '', AUTH_URL: app.config.origin, MCP_URL: app.config.resource, DASHBOARD_URL: dashboard, PUBLISH_URL: publish, PUBLICATION_SERVICE_SECRET: serviceSecret, PUBLICATION_COOKIE_SECRET: cookieSecret, PANEL_CLIENT_ID: client.client_id, PANEL_CLIENT_SECRET: client.client_secret, PORT: String(address.port), HOST: '127.0.0.1' }, stdio: ['ignore', 'pipe', 'pipe'] });
let startupError = '';
child.stderr.on('data', (data: Buffer) => { startupError += data.toString(); });
let browser: Browser | undefined;
const rows = async () => ({ artifacts: await app.db.select().from(artifact), revisions: await app.db.select().from(artifactRevision), publications: await app.db.select().from(artifactPublication), commands: await app.db.select().from(artifactCommand), users: await app.db.select().from(user), sessions: await app.db.select().from(session), panelSessions: await app.db.select().from(panelSession) });
try {
  let ready = false;
  for (let attempt = 0; attempt < 50; attempt++) {
    if (child.exitCode !== null) throw new Error(`Dashboard startup failed: ${startupError.slice(0, 300)}`);
    ready = await fetch(dashboard).then((response) => response.ok).catch(() => false);
    if (ready) break;
    await new Promise((done) => setTimeout(done, 100));
  }
  assert(ready, 'Built Astro panel must start');
  browser = await chromium.launch({ channel: 'chrome' });
  const context = await browser.newContext();
  const setup = await context.newPage();
  await setup.goto(expected.publication!.url);
  await setup.getByLabel('Correo electrónico').fill('owner@example.test');
  await setup.getByLabel('Contraseña').fill(app.password);
  await setup.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await setup.waitForURL(expected.publication!.url);
  await setup.frameLocator('iframe').getByRole('heading', { name: 'Saved retained revision', exact: true }).waitFor();
  const panelUrl = `${dashboard}/artifacts/${encodeURIComponent(expected.artifactId)}?${new URLSearchParams({ revisionId: expected.revision.id })}`;
  await setup.goto(panelUrl);
  await setup.frameLocator('iframe.preview').getByRole('heading', { name: 'Saved retained revision', exact: true }).waitFor();
  await setup.close();
  const before = await rows();
  const requests: { method: string; path: string }[] = [];
  context.on('request', (request) => requests.push({ method: request.method(), path: new URL(request.url()).pathname }));
  const report = await verifyRetainedArtifact(context, { expected, panelUrl, publicationUrl: expected.publication!.url, viewports: [{ width: 1280, height: 900 }, { width: 390, height: 844 }], expectations: [{ kind: 'text', selector: '#total', text: '5.00' }, { kind: 'click', selector: '#change' }, { kind: 'text', selector: '#total', text: '28.40' }], evidenceDirectory: join(evidence, 'verification') });
  assert.equal(report.status, 'passed', JSON.stringify(report.errors));
  assert.equal(report.publication, 'verified');
  assert.deepEqual(report.attachments.map(({ path, bytes }) => ({ path, bytes })), [{ path: 'nested/bytes.bin', bytes: 3 }, { path: 'notes.txt', bytes: 27 }]);
  assert.equal(report.viewports.length, 2);
  const after = await rows();
  assert.deepEqual(after, before, 'Verification must preserve artifact, revision, publication, receipt, user and session rows');
  assert.deepEqual(requests.filter((request) => request.method !== 'GET'), [], 'Verification must issue no browser mutation requests');
  await writeFile(join(evidence, 'no-mutations.json'), `${JSON.stringify({ status: 'passed', requests, rowCounts: Object.fromEntries(Object.entries(before).map(([name, values]) => [name, values.length])), unchanged: Object.keys(before), fixtureBoundary: 'Disposable migrated database, direct store authoring and browser login complete before verification. Verifier uses actual built Astro panel and protected publication handlers.' }, null, 2)}\n`, { mode: 0o600 });
  console.log(JSON.stringify({ status: 'passed', evidence, browserVersion: browser.version(), scope: 'Actual local panel/publication, saved historical revision, exact bytes, content interactions, desktop/mobile, unchanged authoring/account/session rows' }));
} finally {
  await browser?.close();
  child.kill('SIGTERM');
  if (child.exitCode === null) await once(child, 'exit');
  if ('closeAllConnections' in publicationServer) publicationServer.closeAllConnections();
  await new Promise<void>((done) => publicationServer.close(() => done()));
  await app.close();
}
